// Builds src/modules/shearWallWswhData.js from the Simpson Strong-Wall WSWH reference tables
// (Design Item Hub/Shearwall design reference/WSWH, files 01–06).
// Run: node scripts/buildWswhData.mjs "<path to the WSWH folder>"
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir || !fs.existsSync(dir)) {
  console.error('Usage: node scripts/buildWswhData.mjs "<WSWH reference folder>"');
  process.exit(1);
}

// Every markdown table in a file: { heading (last ## / ### line), headers, rows }
function tables(file) {
  const lines = fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/);
  const out = [];
  let heading = '';
  const cellsOf = (l) => l.split('|').slice(1, -1).map(c => c.trim());
  for (let i = 0; i < lines.length; i++) {
    if (/^#{2,3} /.test(lines[i])) heading = lines[i].replace(/^#+ /, '');
    if (!lines[i].startsWith('|') || !lines[i + 1] || !/^\|[-| :]+\|$/.test(lines[i + 1].trim())) continue;
    const headers = cellsOf(lines[i]);
    const rows = [];
    for (i += 2; i < lines.length && lines[i].startsWith('|'); i++) rows.push(cellsOf(lines[i]));
    out.push({ heading, headers, rows });
  }
  return out;
}

// '1,300' → 1300, '26,360 ‡' → 26360, '—' → null, text stays text
function value(c) {
  const t = c.replace(/‡/g, '').replace(/,/g, '').trim();
  if (t === '—' || t === '-' || t === '') return null;
  return /^-?\d+(\.\d+)?$/.test(t) ? Number(t) : c.trim();
}
const objects = (t, keys) => t.rows.map(r => Object.fromEntries((keys || t.headers).map((h, i) => [h, value(r[i] ?? '')])));
const byFirst = (ts, first) => ts.filter(t => t.headers[0] === first);

const t01 = byFirst(tables('01_wswh_concrete.md'), 'model').flatMap(t => objects(t));
const t02 = byFirst(tables('02_wswh_raised_floor.md'), 'model').flatMap(t => objects(t));
const t03 = byFirst(tables('03_wswh_stacked_upper.md'), 'model').flatMap(t => objects(t));
const t05 = tables('05_wswh_geometry.md');
const stocked = objects(byFirst(t05, 'model')[0]);
const evalOrder = objects(byFirst(t05, 'eval_model')[0]);
const arm = objects(byFirst(t05, 'width_in')[0], ['width_in', 'B_concrete_in', 'B_raised_in', 'B_stacked_in']);
const kits = objects(byFirst(t05, 'width_in')[1], ['width_in', 'raisedKit', 'stackedKit']);
const t06 = tables('06_wswh_anchor_tension_cracked.md').filter(t => t.headers[0] === 'criteria').flatMap(t => {
  const fc = Number((t.heading.match(/f'c = ([\d,]+)/) || [])[1].replace(/,/g, ''));
  return objects(t).map(r => ({ fc_psi: fc, ...r }));
});

const check = (name, rows, n) => { if (rows.length !== n) throw new Error(name + ': expected ' + n + ' rows, got ' + rows.length); };
check('T01', t01, 152); check('T02', t02, 28); check('T03', t03, 22); check('T06', t06, 33);
check('05-A', stocked, 19); check('05-B', evalOrder, 28); check('05-C', arm, 3); check('05-D', kits, 3);
for (const r of [...t01, ...t02, ...t03]) if (r.nominal_ft !== Number(r.model.split('x')[1])) throw new Error('nominal_ft mismatch ' + r.model);

const json = (v) => JSON.stringify(v);
const rowsOut = (rows) => '[\n' + rows.map(r => '  ' + json(r)).join(',\n') + ',\n]';
const src = `// GENERATED by scripts/buildWswhData.mjs from the WSWH reference tables
// (Shared Drive: Design Item Hub/Shearwall design reference/WSWH, 00_README + 01–06). Do not edit by hand;
// update the md tables and re-run the script.
// Source: Simpson Strong-Tie C-L-SW26 (© 2026) pp. 38–50, ICC-ES ESR-2652; anchorage web tables (C-L-SW21 images).
// Units: lb, in. _S = seismic, _W = wind. LRFD columns are derived (S = ASD/0.7, W = ASD/0.6), not Simpson-published.

// Table 01 — standard & balloon framing on concrete (pp. 40–41); P axis = ASD vertical load
export const WSWH_T01 = ${rowsOut(t01)};

// Table 02 — first story on a raised wood floor (p. 47); P ≤ 2,000 lb, joist ≤ 12" (× 0.92 for 12"–16")
export const WSWH_T02 = ${rowsOut(t02)};

// Table 03 — two-story stacked, second-story panel (p. 50); no anchor tension published
export const WSWH_T03 = ${rowsOut(t03)};

// Table 05-A — stocked panels (p. 39)
export const WSWH_STOCKED = ${rowsOut(stocked)};

// Table 05-B — evaluation model → order model (trim the next taller stocked panel)
export const WSWH_EVAL_ORDER = ${rowsOut(evalOrder)};

// Table 05-C — anchor moment arm B (in): concrete (p. 41 n.11), raised floor (p. 47 n.8), stacked 2nd story (C-L-SW26 p. 47 n.8, user)
export const WSWH_ARM = ${rowsOut(arm)};

// Table 05-D — connection kits
export const WSWH_KITS = ${rowsOut(kits)};

// Table 06 — WSWH-AB tension anchorage, cracked concrete (f'c 2,500 / 3,000 / 4,500 psi)
// criteria E = SDC C–F (ACI seismic provisions); W/E = SDC A–B and SDC C detached 1–2 family
export const WSWH_ANCHORS = ${rowsOut(t06)};
`;
const outFile = new URL('../src/modules/shearWallWswhData.js', import.meta.url);
fs.writeFileSync(outFile, src);
console.log('wrote', outFile.pathname, '—', t01.length, t02.length, t03.length, t06.length, 'rows');
