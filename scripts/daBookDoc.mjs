// Generates docs/diaphragm-analysis-book-cases.md: every book example, its layout, and each book value against the
// tool value (phases built so far; later phases read "pending (phase N)").
// Run: npm run da:book:doc
import fs from 'node:fs';
import path from 'node:path';
import { loadSources, validate, sheathedArea, parseKey, parseStation, toolValue as toToolSign } from '../tests/td-book/src/lib.mjs';

const repo = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const sources = await loadSources();

// Tool results for the phases built so far (BUILT): the item each example seeds, through the module's calcAll
const BUILT = 6;
const { bookToInputs } = await import('../tests/td-book/src/toInputs.mjs');
const { calcAll, planWithLinks } = await import('../src/modules/diaphragmAnalysis.js');
const { toolValue: bookKeyValue } = await import('../src/modules/tdBookKeys.js');
const runs = new Map();
function toolValue(id, k) {
  const s = sources.find(x => x.id === id), e = s.expected.find(x => x.k === k);
  if (!e || e.phase > BUILT) return undefined;
  if (!runs.has(id)) {
    const inputs = bookToInputs(s);
    inputs.tds.forEach(t => { t.engineer.cantileverOk = true; }); // the book's own design accepts its cantilever TD (Ex 3.4)
    runs.set(id, { plan: planWithLinks(inputs).plan, r: calcAll(inputs) });
  }
  const { plan, r } = runs.get(id);
  const v = bookKeyValue(k, plan, r.analysis);
  return v === null ? NaN : v;
}

const fmt = v => (Math.abs(v) >= 1000 ? v.toLocaleString('en-US', { maximumFractionDigits: 1 }) : String(+v.toFixed(2)));
const side = s => (s === '-' ? ' (left/below)' : s === '+' ? ' (right/above)' : '');
const station = s => { const p = parseStation(s); return (p.at === '*' ? 'full depth' : `grid ${p.at}`) + side(p.side); };
const band = b => (b === '*' ? 'full depth' : `between ${b.replace('-', ' and ')}`);

function describe(k) {
  const { kind, parts: [a, b] } = parseKey(k);
  switch (kind) {
    case 'R': return `force to wall line ${a}`;
    case 'Rw': return `force to wall ${a}`;
    case 'vw': return `unit shear in wall ${a}`;
    case 'V': return `section shear at ${station(a)}`;
    case 'vb': return `basic unit shear at ${station(a)}, ${band(b)}`;
    case 'Nb': return `basic-field force in line ${a} at ${station(b)}`;
    case 'tdR': return `${a} force at support ${b}`;
    case 'vtd': return `${a} unit shear ${band(b)}`;
    case 'vnet': return `net unit shear at ${station(a)}, ${band(b)}`;
    case 'N': return `force in line ${a} at ${station(b)}`;
    case 'Nmax': return `max force in line ${a} ${band(b).replace('between', 'from')}`;
    case 'aspect': return `${a} aspect ratio`;
    default: return k;
  }
}

const out = [];
out.push('# Transfer Diaphragm: book example cases');
out.push('');
out.push('Generated by `npm run da:book:doc` from `tests/td-book/src/Ex*.mjs` (format: `tests/td-book/src/FORMAT.md`).');
out.push('Source: EX-IRREG-2E excerpts in the Shared Drive folder `Diaphragm analysis reference\\book reference`.');
out.push('Pages are 1-based pages of each excerpt PDF. Unit shears use the book\'s "+" sheathing element; member forces are');
out.push('tension + / compression −. The tool must reach the same final values; its route may differ (unit-shear integration, no M/d).');
out.push('');
out.push('| Example | Feature | Values | Phase 4 | 5 | 6 | 7 | Status |');
out.push('|---|---|---|---|---|---|---|---|');
for (const s of sources) {
  const n = p => s.expected.filter(e => e.phase === p).length;
  const errs = validate(s);
  out.push(`| ${s.id} | ${s.title} | ${s.expected.length} | ${n(4)} | ${n(5)} | ${n(6)} | ${n(7)} | ${errs.length ? `${errs.length} format error(s)` : 'transcribed, awaiting review'} |`);
}
out.push('');

for (const s of sources) {
  const L = s.layout;
  out.push(`## ${s.id}: ${s.title}`);
  out.push('');
  out.push(`PDF \`${s.pdf}\`, pages ${s.pages}.${s.shearElement === 'mirrored' ? ' **Mirrored "+" element:** unit shears are shown as printed; the "Tool sign" column is the Ex 4.1 convention the tool uses.' : ''}`);
  out.push('');
  const gx = L.grids.filter(g => g.axis === 'x').map(g => `${g.name} @ ${g.at}`).join(', ');
  const gy = L.grids.filter(g => g.axis === 'y').map(g => `${g.name} @ ${g.at}`).join(', ');
  out.push(`- **Grids** x: ${gx}; y: ${gy}`);
  out.push(`- **Outline** ${L.outline.map(p => `(${p[0]}, ${p[1]})`).join(' → ')}; sheathed area ${sheathedArea(L)} sf`);
  if ((L.openings || []).length) out.push(`- **Openings** ${L.openings.map(o => `${o.name || ''} x ${o.x[0]}–${o.x[1]}, y ${o.y[0]}–${o.y[1]}`).join('; ')}`);
  out.push(`- **Walls** ${(L.walls || []).map(w => `${w.mark} (line ${w.line}, ${w.axis} = ${w.at}, ${w.from}–${w.to})`).join('; ') || 'none'}`);
  out.push(`- **TDs** ${(L.tds || []).map(t => `${t.mark} x ${t.x[0]}–${t.x[1]}, y ${t.y[0]}–${t.y[1]}, supports ${t.supports.join(' / ')}, loads ${t.loads.map(l => `${l.grid} (${l.side})`).join(', ')}${t.overhang ? `, overhang ${t.overhang.join('–')}` : ''}`).join('; ') || 'none'}`);
  out.push(`- **Load** ${(L.loads || []).map(l => `${l.mode} acting ${l.acts}: ${(l.segments || []).map(g => `${g.w}${g.w2 !== undefined ? '→' + g.w2 : ''} ${l.mode === 'area' ? 'psf' : 'plf'} over ${g.from}–${g.to}`).join(', ')}`).join('; ')}`);
  out.push('');
  out.push('| # | Quantity | Key | Book | Tool sign | Unit | T/C | Page (fig) | Phase | Tool | Status |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|');
  s.expected.forEach((e, i) => {
    const t = toolValue(s.id, e.k);
    const want = toToolSign(s, e);
    const status = t === undefined ? `pending (phase ${e.phase})` : (Math.abs(t - want) <= (e.tol ?? Math.max(0.005 * Math.abs(want), 0.5)) ? 'ok' : 'DIFF');
    out.push(`| ${i + 1} | ${describe(e.k)}${e.note ? ` (${e.note})` : ''} | \`${e.k}\` | ${fmt(e.v)} | ${fmt(want)} | ${e.unit} | ${e.sense || ''} | ${e.page}${e.fig ? ` (${e.fig})` : ''} | ${e.phase} | ${t === undefined ? '—' : fmt(t)} | ${status} |`);
  });
  out.push('');
  if ((s.errata || []).length) {
    out.push('**Errata**');
    s.errata.forEach(e => out.push(`- p${e.page}: ${e.what} Used: ${e.use}.`));
    out.push('');
  }
  if ((s.assumptions || []).length) {
    out.push('**Assumptions (not given by the book)**');
    s.assumptions.forEach(a => out.push(`- ${a.what} (${a.why})`));
    out.push('');
  }
  if ((s.expectedNonClosing || []).length) {
    out.push(`**Non-closing first distribution (book shows it does not close):** ${s.expectedNonClosing.length} values, kept in the source.`);
    out.push('');
  }
}

const file = path.join(repo, 'docs', 'diaphragm-analysis-book-cases.md');
fs.writeFileSync(file, out.join('\n'));
console.log('wrote', path.relative(repo, file), `(${sources.length} examples)`);
