// Builds src/modules/shearWallSswhData.js from the Simpson Strong-Wall SSWH (high-strength steel shearwall) reference
// tables (Design Item Hub/Shearwall design reference/SSWH, files 11–16; reviewed by the user 2026-11-10).
// Run: node scripts/buildSswhData.mjs "<path to the SSWH folder>"   (npm run sswh:build)
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir || !fs.existsSync(dir)) {
  console.error('Usage: node scripts/buildSswhData.mjs "<SSWH reference folder>"');
  process.exit(1);
}

// Every markdown table in a file: { heading (last ## / ### line), headers, rows } — same reader as buildWswhData.mjs
function tables(file) {
  const lines = fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/);
  const out = [];
  let heading = '';
  const cellsOf = (l) => l.split('|').slice(1, -1).map(c => c.trim());
  for (let i = 0; i < lines.length; i++) {
    if (/^#{2,3} /.test(lines[i])) heading = lines[i].replace(/^#+ /, '');
    if (!lines[i].startsWith('|') || !lines[i + 1] || !/^\|[-| :]+\|$/.test(lines[i + 1].trim())) continue;
    const headers = cellsOf(lines[i]);
    const rows = [];
    for (i += 2; i < lines.length && lines[i].startsWith('|'); i++) rows.push(cellsOf(lines[i]));
    out.push({ heading, headers, rows });
  }
  return out;
}
function value(c) {
  const t = c.replace(/,/g, '').trim();
  if (t === '—' || t === '-' || t === '') return null;
  return /^-?\d+(\.\d+)?$/.test(t) ? Number(t) : c.trim();
}
const objects = (t, keys) => t.rows.map(r => Object.fromEntries((keys || t.headers).map((h, i) => [h, value(r[i] ?? '')])));
const byFirst = (ts, first) => ts.filter(t => t.headers[0] === first);
const design = (file) => byFirst(tables(file), 'model').filter(t => /Design values/.test(t.heading)).flatMap(t => objects(t));

const t11 = design('11_sswh_concrete.md');
const t12 = design('12_sswh_portal.md');
const t13 = design('13_sswh_wood_floor.md');
const t14 = design('14_sswh_stacked_upper.md');
const t15 = design('15_sswh_stacked_first_story.md');
const t16 = tables('16_sswh_geometry.md');
const arm = objects(byFirst(t16, 'width_in')[0]);
const kits = objects(byFirst(t16, 'width_in')[1]);

const check = (name, rows, n) => { if (rows.length !== n) throw new Error(name + ': expected ' + n + ' rows, got ' + rows.length); };
check('T11', t11, 204); check('T12', t12, 36); check('T13', t13, 34); check('T14', t14, 34); check('T15', t15, 34);
check('16-C', arm, 5); check('16-D', kits, 5);
for (const r of [...t11, ...t12, ...t13, ...t14, ...t15]) if (r.nominal_ft !== Number(r.model.split('x')[1])) throw new Error('nominal_ft mismatch ' + r.model);

const json = (v) => JSON.stringify(v);
const rowsOut = (rows) => '[\n' + rows.map(r => '  ' + json(r)).join(',\n') + ',\n]';
const src = `// GENERATED by scripts/buildSswhData.mjs from the SSWH reference tables
// (Shared Drive: Design Item Hub/Shearwall design reference/SSWH, 00_README + 11–16). Do not edit by hand;
// update the md tables and re-run the script.
// Source: Simpson Strong-Tie C-L-SW26 (© 2026) pp. 11–29, ICC-ES ESR-1679 (2021 IBC confirmed by the user 2026-11-10).
// Units: lb, in. _S = seismic, _W = wind. LRFD columns are derived (S = ASD/0.7, W = ASD/0.6), not Simpson-published.

// Table 11 — standard application on concrete (pp. 13–15); P axis = ASD vertical load (1,000 / 4,000 / 7,500 lb)
export const SSWH_T11 = ${rowsOut(t11)};

// Table 12 — garage portal, single wall with SSWH-PKT (p. 19); T = k·V·H/B − P/2
export const SSWH_T12 = ${rowsOut(t12)};

// Table 13 — first story on a wood floor (p. 21); P ≤ 2,000 lb; joist ≤ 12" (× 0.91 to 16"); DFL rim × 0.84
export const SSWH_T13 = ${rowsOut(t13)};

// Table 14 — two-story stacked, second-story panel (p. 28); joist 14" (× 0.96 to 18"); DFL rim × 0.95; no T published
export const SSWH_T14 = ${rowsOut(t14)};

// Table 15 — two-story stacked, first-story -STK panel: allowable base moment M (lb-ft), drift and T at M (p. 27)
export const SSWH_T15 = ${rowsOut(t15)};

// Table 16-C — anchor moment arm B (in). Concrete / stack base: p. 15 n.9 as printed (user 2026-11-10; the tables imply
// 8⅛ / 10⅜ / 12⅝ for SSWH12 / 15 / 18 — follow up with Simpson). Portal p. 19 n.10; wood floor W − 4 (p. 21 n.9).
export const SSWH_ARM = ${rowsOut(arm)};

// Table 16-D — connection kits
export const SSWH_KITS = ${rowsOut(kits)};
`;
const outFile = new URL('../src/modules/shearWallSswhData.js', import.meta.url);
fs.writeFileSync(outFile, src);
console.log('wrote', outFile.pathname, '—', t11.length, t12.length, t13.length, t14.length, t15.length, 'rows');
