// Generate the verification case catalog the engineer reviews: docs/shear-wall-test-cases.md
//   npm run cases:doc
// One section per METHOD case (tests/cases/Vxx-*.json): intent, model with the pinned design, hand calc, expected vs
// calculated, checks — plus the list of design selection rules that are tested automatically (not hand-checked).
// The calculated column is the current engine, so the catalog always shows where the tool stands.
import fs from 'fs';
import './lib/shearWallLoadCheck.mjs'; // stand-in DOM for the module imports
import { calcAll, CALC_VERSION } from '../src/modules/shearWallCalc.js';
import { shearWallDesign } from '../src/modules/shearWallDesign.js';
import { evaluateCase, fmtValue, modelSummary } from '../src/modules/shearWallVerify.js';
import { pinnedText } from '../tests/cases/src/lib.mjs';

const casesDir = new URL('../tests/cases/', import.meta.url);
const outFile = new URL('../docs/shear-wall-test-cases.md', import.meta.url);
const cases = fs.readdirSync(casesDir).filter(f => /^V\d\d-.*\.json$/.test(f)).sort()
  .map(f => JSON.parse(fs.readFileSync(new URL(f, casesDir), 'utf8')));
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const results = cases.map(c => {
  const inp = shearWallDesign.migrate({ schemaVersion: c.schemaVersion, inputs: JSON.parse(JSON.stringify(c.inputs)) }).inputs;
  return { c, inp, ev: evaluateCase(c, calcAll(inp)) };
});

const md = [];
md.push('# Shear Wall Design — method verification cases');
md.push('');
md.push('Generated by `npm run cases:doc` from `tests/cases/*.json` (sources with the hand-calc arithmetic: `tests/cases/src/`). Engine: calc ' + CALC_VERSION + ', schema ' + shearWallDesign.schemaVersion + '.');
md.push('');
md.push('**What this document verifies — the method, not the design choices.** Each case fixes (pins) its design — nailing, holdowns / straps, posts, anchors — as manual overrides, listed under *Given (pinned)*. The case then checks how the tool calculates: loads, shares, end forces T / C per load case, load combinations, stacking and transfer, deflection and drift, and demand ≤ capacity of the pinned parts. A change to the design selection logic (e.g. drift sizing or minimum posts) does not change these cases. Where a hand-calc step names a size, it explains why the pinned part is adequate.');
md.push('');
md.push('**Three layers of testing:** (1) this catalog — the method, reviewed by the engineer; (2) the design selection rules R1–R7 below — automated property tests on every model (`tests/shearWallRules.test.mjs`, `tests/shearWallDrift.test.mjs`), any valid design passes; (3) golden output — a change detector (`npm run cases:diff` shows what changed, `npm run cases:accept` records it). The in-app checks G1–G12 are separate: they run on every project and prove each result balances.');
md.push('');
md.push('**How to review a case:** read the intent and the model, follow the hand calc, then compare the *Expected* column (hand calc) with *Calculated* (the tool now). The same case is in the local project **SW Verification** (`npm run seed:cases`) — open it and use the **Verification** tab, or Walls → Detailed for the calc sheet.');
md.push('');
md.push('**Sign convention:** N = vertical force at a wall end (k), + = compression, − = uplift. → = shear toward the right end (left end uplift). Load cases 1.0D / 1.0L / 1.0Lr / 1.0E / 1.0W are unfactored.');
md.push('');
md.push('**Every case also runs** (`npm test`): T1 line checks G1–G12 · T2 these values · T3 C3 = C4 = the tool and C5 superposition = governing · T4 every tab / calc sheet / elevation / PDF renders · T5 golden output (`tests/cases/golden/`, refreshed with `npm run cases:accept` after review).');
md.push('');
md.push('**Design selection rules R1–R8 (automated tests, not hand-checked).** V05, V06, V07 and V16 moved here as rule models.');
md.push('');
for (const t of [
  'R1 — Auto nailing = the lightest pattern with v ≤ v_cap·C_hb (seismic and wind); raised for drift → heavier than the strength pick.',
  'R2 — Auto holdown / strap = the lightest in its table (HDUE; MSTC by floor clear span) with cap ≥ T; OVER only when none carries T; raised for drift → larger than the strength pick.',
  'R3 — Auto post = the first in catalog order with cap ≥ C and at least the anchorage minimum post (HDUE by size; MSTC floor straps (2)2x).',
  'R4 — Overrides are never changed; a post override below the minimum post is replaced and flagged.',
  'R5 — Support-post members are designed for max(ASD, Ω₀ ASD) compression, then R3.',
  'R6 — WSWH anchor = the smallest footing width W, then embedment d_e, with T_allow ≥ T among the SDC-permitted rows.',
  'R7 — Drift sizing: each failing story gets the step that cuts the governing wall’s δ more (story nailing step, or that wall’s holdown / strap one size up) until it passes or nothing is left; a nailing step keeps one common pattern per story; bypass reports only.',
  'R8 — Deflection distribution: at every story each wall with a share gives the same SDPWS Eq. 4.3-1 δ*, Σ V = the story shear; a wall the forces from above already displace more than δ* takes no share; a note when δ(0)/δ* > 0.5.',
]) md.push('- ' + t);
md.push('');
md.push('| Case | Title | Covers | Values | Checks | Result |');
md.push('|---|---|---|---|---|---|');
for (const { c, ev } of results) {
  const nv = ev.values.length, ok = ev.values.filter(v => v.pass).length;
  const must = (c.expectChecks && c.expectChecks.fail) || [];
  md.push('| [' + c.id + '](#' + c.id.toLowerCase() + ') | ' + cell(c.title) + ' | ' + cell((c.covers || []).join(', ')) + ' | ' + ok + ' / ' + nv + ' | ' + (must.length ? must.join(', ') + ' must fail' : 'all pass') + ' | ' + (ev.pass ? 'PASS' : '**FAIL**') + ' |');
}
for (const { c, inp, ev } of results) {
  md.push('');
  md.push('<a id="' + c.id.toLowerCase() + '"></a>');
  md.push('## ' + c.id + ' — ' + c.title + ' ' + (ev.pass ? '(PASS)' : '(**FAIL**)'));
  md.push('');
  md.push('**Intent.** ' + c.intent);
  md.push('');
  if ((c.covers || []).length) { md.push('**Covers.** ' + c.covers.join(' · ')); md.push(''); }
  md.push('**Model.**');
  md.push('');
  md.push('```');
  modelSummary(inp).forEach(l => md.push(l));
  md.push('```');
  const pins = pinnedText(c.pinned);
  if (pins.length) { md.push(''); md.push('**Given (pinned).** ' + pins.join(' · ')); }
  md.push('');
  md.push('**Hand calc.**');
  md.push('');
  c.handCalc.forEach(s => md.push(s.step + '. ' + s.text));
  md.push('');
  md.push('**Expected (hand calc) vs calculated (tool).**');
  md.push('');
  md.push('| Step | Value | Expected | Calculated | Difference | Tolerance | |');
  md.push('|---|---|---|---|---|---|---|');
  for (const v of ev.values) {
    md.push('| ' + v.step + ' | ' + cell(v.label) + ' | ' + cell(fmtValue(v.value)) + ' | ' + cell(v.error ? v.error : fmtValue(v.actual)) + ' | ' + (v.diff != null ? v.diff.toFixed(4) : '') + ' | ' + (v.tol != null ? v.tol : '') + ' | ' + (v.pass ? 'OK' : '**NG**') + ' |');
  }
  md.push('');
  const must = (c.expectChecks && c.expectChecks.fail) || [];
  const badChecks = ev.checks.filter(x => !x.pass);
  md.push('**Line checks G1–G12.** ' + (must.length ? must.join(', ') + ' must fail (see intent); every other check must pass. ' : 'Every check must pass. ')
    + (badChecks.length ? '**Not as expected:** ' + badChecks.map(x => x.line + ' ' + x.id + ' ' + x.status).join(', ') + '.' : 'As expected.')
    + (ev.warnings.length ? ' Required audit warnings: ' + ev.warnings.map(w => w.type + (w.pass ? '' : ' (**missing**)')).join(', ') + '.' : ''));
  if (c.notChecked) { md.push(''); md.push('**Not hand-checked here.** ' + c.notChecked); }
}
md.push('');
fs.writeFileSync(outFile, md.join('\n'));
const fails = results.filter(r => !r.ev.pass).map(r => r.c.id);
console.log('Wrote docs/shear-wall-test-cases.md — ' + results.length + ' cases' + (fails.length ? ', FAIL: ' + fails.join(', ') : ', all pass'));
